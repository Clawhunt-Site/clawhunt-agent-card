"""Generate main/ground_strips.c: the colour fields the screens stand on.

The panel shows 16-bit colour (5 bits of red and blue, 6 of green). A gradient drawn straight into that has steps: blue
to white over the screen's height is 24 steps of red, each a band ten pixels tall. So every ground is drawn here,
dithered (an 8x8 ordered pattern between the two nearest 16-bit colours), and stored as one strip 16 pixels wide and
as tall as the screen. A screen repeats its strip across its width (LVGL: a tiled background image), which costs
10 kB of flash a ground instead of 150 kB.

Usage:
    python tools/gen_grounds.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_C = ROOT / "main" / "ground_strips.c"
OUT_H = ROOT / "main" / "ground_strips.h"

WIDTH = 16
HEIGHT = 320

# The brand's colours (main/ui_card.c names the same values): change them together.
BLUE = 0x3F7FF5
BLUE_DEEP = 0x2496DF
TEAL = 0x10B6A6
MINT = 0xC6FDF1
INK = 0x0E1C2C
WHITE = 0xFFFFFF
NIGHT = 0x1D4F8C  # the foot of the setup ground: ink lifted towards the brand's blue
SLATE = 0x4F6477
SLATE_DEEP = 0x3D5062

# name, what stands on it, stops as (position 0..1 down the screen, colour)
GROUNDS = [
    ("ground_home", "the card at rest: blue at the top, white at the foot",
     [(0.0, BLUE), (0.06, BLUE), (0.94, WHITE), (1.0, WHITE)]),
    ("ground_ask", "something wants an answer: a payment request, the secret, a new order",
     [(0.0, BLUE), (1.0, BLUE_DEEP)]),
    ("ground_done", "it went through: confirmed, paid in, connected",
     [(0.0, TEAL), (1.0, MINT)]),
    ("ground_setup", "setting the card up: its code, its menu, its hotspot",
     [(0.0, INK), (1.0, NIGHT)]),
    ("ground_none", "nothing happened: missed, refused, failed",
     [(0.0, SLATE), (1.0, SLATE_DEEP)]),
]

BAYER8 = [
    [0, 32, 8, 40, 2, 34, 10, 42],
    [48, 16, 56, 24, 50, 18, 58, 26],
    [12, 44, 4, 36, 14, 46, 6, 38],
    [60, 28, 52, 20, 62, 30, 54, 22],
    [3, 35, 11, 43, 1, 33, 9, 41],
    [51, 19, 59, 27, 49, 17, 57, 25],
    [15, 47, 7, 39, 13, 45, 5, 37],
    [63, 31, 55, 23, 61, 29, 53, 21],
]


def channels(rgb: int) -> tuple:
    return (rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF


def colour_at(stops: list, t: float) -> tuple:
    for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
        if t <= p1:
            k = 0.0 if p1 == p0 else (t - p0) / (p1 - p0)
            a, b = channels(c0), channels(c1)
            return tuple(a[i] + (b[i] - a[i]) * k for i in range(3))
    return tuple(float(v) for v in channels(stops[-1][1]))


def quantise(value: float, levels: int, threshold: float) -> int:
    """One channel to 0..levels, the ordered pattern deciding between the two nearest."""
    scaled = value / 255.0 * levels
    return max(0, min(levels, int(scaled + threshold)))


def render(stops: list) -> list:
    pixels = []
    for y in range(HEIGHT):
        r, g, b = colour_at(stops, y / (HEIGHT - 1))
        for x in range(WIDTH):
            threshold = (BAYER8[y % 8][x % 8] + 0.5) / 64.0
            r5, g6, b5 = quantise(r, 31, threshold), quantise(g, 63, threshold), quantise(b, 31, threshold)
            pixels.append((r5 << 11) | (g6 << 5) | b5)
    return pixels


def emit(name: str, pixels: list) -> str:
    data = []
    for value in pixels:
        data += ["0x%02x" % (value & 0xFF), "0x%02x" % (value >> 8)]
    body = ",\n    ".join(", ".join(data[i : i + 16]) for i in range(0, len(data), 16))
    return (
        f"static const uint8_t s_{name}[] = {{\n    {body}\n}};\n\n"
        f"const lv_image_dsc_t {name} = {{\n"
        "    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n"
        f"                .w = {WIDTH}, .h = {HEIGHT}, .stride = {WIDTH * 2} }},\n"
        f"    .data_size = sizeof(s_{name}),\n"
        f"    .data = s_{name},\n"
        "};\n"
    )


def main() -> None:
    parts = [emit(name, render(stops)) for name, _, stops in GROUNDS]
    text = "// Generated by tools/gen_grounds.py. Do not edit by hand.\n" '#include "ground_strips.h"\n\n' + "\n".join(parts)
    OUT_C.write_bytes(text.encode("utf-8"))
    lines = [
        "// main/ground_strips.h -- the colour fields the screens stand on (see tools/gen_grounds.py).",
        "// Each is a strip GROUND_STRIP_W wide and as tall as the screen, dithered for the 16-bit panel; a screen",
        "// repeats it across its width.",
        "#pragma once",
        "",
        '#include "lvgl.h"',
        "",
        f"#define GROUND_STRIP_W {WIDTH}",
        "",
    ]
    for name, what, _ in GROUNDS:
        lines.append(f"extern const lv_image_dsc_t {name};   // {what}")
    OUT_H.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"{len(GROUNDS)} grounds, {WIDTH}x{HEIGHT} each, {len(GROUNDS) * WIDTH * HEIGHT * 2} bytes")


if __name__ == "__main__":
    main()
