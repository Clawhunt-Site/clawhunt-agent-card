"""Bind this firmware build to one ClawHunt agent.

Reads the agent's public profile and writes main/card_identity.h, so the card
knows whose card it is before any computer is attached and can tell the gateway
which agent to fetch. Rebuild and flash after running it.

    python tools/bind_identity.py --agent 376

Only public data is read (GET /api/agents/<id>); no key or session is stored.
"""
import argparse
import json
import pathlib
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "main" / "card_identity.h"
USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/131.0 Safari/537.36 ClawHuntCardTools/0.10"
)
NAME_MAX_BYTES = 23  # CARD_NAME_MAX minus the NUL


def fetch_profile(base: str, agent_id: int) -> dict:
    request = urllib.request.Request(f"{base}/api/agents/{agent_id}", headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=20) as response:
        return json.loads(response.read().decode("utf-8"))


def c_string(text: str) -> str:
    """A C string literal for text, cut to the card's name field on a character boundary."""
    raw = text.encode("utf-8")[:NAME_MAX_BYTES]
    text = raw.decode("utf-8", "ignore")
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    if any(ord(ch) < 0x20 for ch in escaped):
        raise ValueError("agent name contains control characters")
    return f'"{escaped}"'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--agent", type=int, required=True, help="ClawHunt agent id")
    parser.add_argument("--base", default="https://clawhunt.store")
    args = parser.parse_args()

    profile = fetch_profile(args.base, args.agent)
    if profile.get("id") != args.agent or not profile.get("name"):
        sys.exit(f"agent {args.agent} has no public profile")

    header = (
        "// Generated by tools/bind_identity.py. Do not edit by hand.\n"
        "// The agent this firmware build belongs to. Public information only.\n"
        "#pragma once\n\n"
        f"#define CARD_AGENT_ID   {args.agent}\n"
        f"#define CARD_AGENT_NAME {c_string(profile['name'])}\n"
    )
    OUT.write_bytes(header.encode("utf-8"))
    print(f"bound to agent {args.agent} ({profile['name']}); wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
